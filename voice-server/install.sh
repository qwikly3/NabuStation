#!/usr/bin/env bash
# NabuStation: install the voice server on the Home Assistant host.
#
# Run as the user that will own the service (not root):
#   ./voice-server/install.sh
#
# It creates ~/nabustation/voice, a virtualenv, voice.env, ha_token.txt and a
# systemd --user unit.  It does not install Home Assistant or Silero TTS.
set -euo pipefail

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
INSTALL_DIR="${INSTALL_DIR:-$HOME/nabustation/voice}"
FORCE=0
[ "${1:-}" = "--force" ] && FORCE=1

if [ "$(id -u)" -eq 0 ]; then
  echo "Run as the HA user, not root. The service is a systemd --user unit." >&2
  exit 1
fi

ask() {
  local var="$1" prompt="$2" default="$3" value
  value="${!var:-}"
  if [ -n "$value" ]; then
    printf -v "$var" '%s' "$value"
    return
  fi
  if [ -t 0 ]; then
    read -r -p "$prompt [$default]: " value
  fi
  [ -n "$value" ] || value="$default"
  printf -v "$var" '%s' "$value"
}

if [ -f "$INSTALL_DIR/voice.env" ] && [ "$FORCE" -ne 1 ]; then
  echo "$INSTALL_DIR/voice.env already exists; use --force to rewrite." >&2
  exit 1
fi

STATION_HOST="${STATION_HOST:-}"
HA_HOST="${HA_HOST:-127.0.0.1}"
MUSIC_ENTITY="${MUSIC_ENTITY:-media_player.station_1}"
SILERO_URL="${SILERO_URL:-http://127.0.0.1:10400/tts}"
PIPELINE_NAME="${PIPELINE_NAME:-}"

if [ -z "$STATION_HOST" ]; then
  ask STATION_HOST "Station 1 IP" "192.168.1.10"
fi
ask HA_HOST "Home Assistant host" "127.0.0.1"
ask MUSIC_ENTITY "Music Assistant player entity" "media_player.station_1"
ask SILERO_URL "Silero TTS URL" "http://127.0.0.1:10400/tts"
if [ -t 0 ]; then
  read -r -p "HA pipeline name (empty = preferred): " PIPELINE_NAME
fi

echo "==> Checking Python and SpeexDSP"
python3 -m venv --help >/dev/null 2>&1 || {
  echo "python3-venv is missing. Install it first (sudo apt install python3-venv)." >&2
  exit 1
}
if ! ldconfig -p 2>/dev/null | grep -q speexdsp; then
  echo "WARNING: libspeexdsp not found. Install libspeexdsp1 for the good AEC." >&2
  echo "         The service will fall back to the FIR AEC." >&2
fi

echo "==> Creating $INSTALL_DIR"
mkdir -p "$INSTALL_DIR"
if [ -d "$INSTALL_DIR/venv" ]; then
  :
else
  python3 -m venv "$INSTALL_DIR/venv"
fi
"$INSTALL_DIR/venv/bin/pip" install --upgrade pip
"$INSTALL_DIR/venv/bin/pip" install -r "$SCRIPT_DIR/requirements.txt"

echo "==> Installing files"
for f in station_voice.py speex_aec.py aec.py; do
  if [ -f "$INSTALL_DIR/$f" ]; then
    cp -a "$INSTALL_DIR/$f" "$INSTALL_DIR/$f.bak-$(date +%Y%m%d-%H%M%S)"
  fi
  cp -a "$SCRIPT_DIR/$f" "$INSTALL_DIR/$f"
done

TOKEN_FILE="$INSTALL_DIR/ha_token.txt"
if [ -n "${HA_TOKEN:-}" ]; then
  printf '%s\n' "$HA_TOKEN" > "$TOKEN_FILE"
elif [ -t 0 ]; then
  echo
  echo "Create a long-lived token in HA: Profile -> Security -> Long-lived access tokens."
  read -r -s -p "Paste HA token: " HA_TOKEN
  echo
  printf '%s\n' "$HA_TOKEN" > "$TOKEN_FILE"
else
  echo "Set HA_TOKEN or run interactively to write $TOKEN_FILE." >&2
  exit 1
fi
chmod 600 "$TOKEN_FILE"

cat > "$INSTALL_DIR/voice.env" <<EOF
# Generated by NabuStation voice-server/install.sh
STATION_HOST=$STATION_HOST
MIC_PORT=8091
PLAY_PORT=8092
LED_PORT=8093
BUTTON_PORT=8095
COMMAND_PORT=8096
CONTROL_PORT=8090
CONTROL_BIND=0.0.0.0
DEBIAN_VOLUME_URL=http://$STATION_HOST:8098
STATION_VOLUME_DEFAULT=5
HA_HOST=$HA_HOST
HA_TOKEN_FILE=$TOKEN_FILE
PIPELINE_NAME=$PIPELINE_NAME
MUSIC_ENTITY=$MUSIC_ENTITY
MUSIC_DUCK_LOUD=0.15
MUSIC_DUCK_QUIET=0.05
MUSIC_DUCK_THRESHOLD=15
SILERO_URL=$SILERO_URL
SILERO_VOICE=eugene
TTS_RATE=48000
TTS_GAIN=0.9
MIC_ORDER=debian
MIC_GAIN=14
MUSIC_REF_RMS=10
WAKE_DUCK_RMS=100000
WAKE_THRESHOLD=0.15
WAKE_THRESHOLD_MUSIC=0.15
WAKE_HITS_MIN=1
WAKE_HIGH=0.75
WAKE_HIGH_MUSIC=0.7
EOF
chmod 600 "$INSTALL_DIR/voice.env"

echo "==> Installing systemd user unit"
mkdir -p "$HOME/.config/systemd/user"
sed "s|%h/nabustation/voice|$INSTALL_DIR|g" \
  "$SCRIPT_DIR/systemd/station-voice.service" \
  > "$HOME/.config/systemd/user/station-voice.service"
systemctl --user daemon-reload
systemctl --user enable --now station-voice.service
systemctl --user --no-pager status station-voice.service || true

echo
echo "Voice server installed."
echo "  Config:  $INSTALL_DIR/voice.env"
echo "  Token:   $TOKEN_FILE"
echo "  Control: http://<ha-host>:8090 (PTT/SAY/health)"
echo "  Logs:    journalctl --user -u station-voice.service -f"
echo
echo "If the user service stops when you log out:"
echo "  sudo loginctl enable-linger $USER"
echo
echo "Next: start the Silero TTS container and check:"
echo "  curl '$SILERO_URL?text=привет&speaker=eugene&sr=48000' -o /tmp/tts.wav"
